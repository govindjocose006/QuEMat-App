 'noticeColumn',EXISTS(SELECT 1 FROM pg_attribute WHERE attrelid='public.notifications'::regclass AND attname='notice_id' AND NOT attisdropped),
 'newColumnsNullableText',(SELECT count(*)=2 FROM pg_attribute WHERE attrelid='public.notifications'::regclass AND attname IN ('meeting_id','notice_id') AND NOT attisdropped AND NOT attnotnull AND atttypid='text'::regtype),
 'phase3cSource',EXISTS(SELECT 1 FROM pg_constraint WHERE conrelid='public.notifications'::regclass AND conname='notification_source' AND contype='c' AND convalidated AND regexp_replace(pg_get_constraintdef(oid),'[[:space:]]','','g')=regexp_replace('CHECK ((num_nonnulls(booking_id, weekly_report_id, issue_id, meeting_id, notice_id) = 1))','[[:space:]]','','g'))
 ),
 'counts',(baseline.state->'counts') || jsonb_build_object('issues',(SELECT count(*) FROM public.issues),'issueEvents',(SELECT count(*) FROM public.issue_events),'issueComments',(SELECT count(*) FROM public.issue_comments))
) AS state FROM baseline;
