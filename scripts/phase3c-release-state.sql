 'collaborationFunctionBodies',(SELECT jsonb_object_agg(e.name,EXISTS(SELECT 1 FROM pg_proc p WHERE p.oid=to_regprocedure('public.'||e.name) AND NOT p.prosecdef AND p.prorettype='trigger'::regtype AND encode(sha256(convert_to(replace(p.prosrc,chr(13)||chr(10),chr(10)),'UTF8')),'hex')=e.hash)) FROM collaboration_functions e),
 'collaborationTriggers',(SELECT jsonb_object_agg(e.name,EXISTS(SELECT 1 FROM pg_trigger t WHERE t.tgname=e.name AND t.tgrelid=to_regclass('public.'||e.relation) AND NOT t.tgisinternal)) FROM collaboration_triggers e),
 'collaborationTriggersEnabled',(SELECT jsonb_object_agg(e.name,EXISTS(SELECT 1 FROM pg_trigger t WHERE t.tgname=e.name AND t.tgrelid=to_regclass('public.'||e.relation) AND t.tgfoid=to_regprocedure('public.'||e.function_name) AND t.tgenabled IN ('O','A') AND t.tgtype=27 AND NOT t.tgisinternal)) FROM collaboration_triggers e),
 'collaborationIndexes',(SELECT jsonb_object_agg(name,to_regclass('public.'||name) IS NOT NULL) FROM collaboration_indexes),
 'collaborationIndexesValid',(SELECT jsonb_object_agg(e.name,EXISTS(SELECT 1 FROM pg_index i WHERE i.indexrelid=to_regclass('public.'||e.name) AND i.indisvalid AND i.indisready AND regexp_replace(pg_get_indexdef(i.indexrelid),'[[:space:]]','','g')=regexp_replace(e.definition,'[[:space:]]','','g'))) FROM collaboration_indexes e),
 'collaborationConstraints',(SELECT jsonb_object_agg(e.relation||'.'||e.name,EXISTS(SELECT 1 FROM pg_constraint c WHERE c.conname=e.name AND c.conrelid=to_regclass('public.'||e.relation))) FROM collaboration_constraints e),
 'collaborationConstraintsValid',(SELECT jsonb_object_agg(e.relation||'.'||e.name,EXISTS(SELECT 1 FROM pg_constraint c WHERE c.conname=e.name AND c.conrelid=to_regclass('public.'||e.relation) AND c.contype::text=e.kind AND c.convalidated AND regexp_replace(pg_get_constraintdef(c.oid),'[[:space:]]','','g')=regexp_replace(e.definition,'[[:space:]]','','g'))) FROM collaboration_constraints e),
